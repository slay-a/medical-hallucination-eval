"""ch_mimic.py — Chapter 7: Main Study: Results on MIMIC-IV Hospital Courses (local model, validated judge)."""
from pathlib import Path

import numpy as np
import pandas as pd

from results_loader import Results, f2, f3, pct, pct0, fp, fpn, signed

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
NAME = {"E0": "E0 zero-context LLM", "E1": "E1 RAG (excerpts only, cited)", "E1b": "E1b RAG (course + excerpts, cited)", "E3": "E3 RAG + CoVe",
        "E2": "E2 extractive", "REF": "Doctor-written instructions"}
ORDER = ["E0", "E1", "E1b", "E3", "E2", "REF"]
VAR = {"base": "E1 base (5-sentence chunks, top-3, dense, cited)", "chunk3": "3-sentence chunks", "chunk8": "8-sentence chunks", "top2": "top-2 chunks",
       "top5": "top-5 chunks", "bm25": "BM25 retrieval", "nocite": "citations not required"}


def P(t):
    return ("p", t)


def _csv(name):
    f = RES / name
    return pd.read_csv(f) if f.exists() else None


def direction(t, metric_lower_is_better=True):
    if t is None or (isinstance(t.p, float) and np.isnan(t.p)):
        return "did not differ from"
    if t.p >= 0.05:
        return "did not differ significantly from"
    return "was lower than" if t.delta_mean < 0 else "was higher than"


def blocks(R: Results) -> list:
    summ, tests, abl, ref, qa = _csv("mimic_summary.csv"), _csv("mimic_pairwise_tests.csv"), _csv("mimic_ablations.csv"), _csv("mimic_reference.csv"), _csv("mimic_qa_summary.csv")
    b = [("h1", "Chapter 7 Main Study: Results on MIMIC-IV Hospital Courses")]
    if summ is None:
        b += [P("The main study has not been evaluated yet.")]
        return b
    base = summ[summ.variant == "base"].set_index("condition")
    conds = [c for c in ORDER if c in base.index]
    judge, mode, tau = summ.judge.iloc[0], summ["mode"].iloc[0], summ.tau.iloc[0]

    def T(metric, comp):
        t = tests[(tests.metric == metric) & (tests.comparison == comp)]
        return t.iloc[0] if len(t) else None

    b += [("h2", "7.1 Setting")]
    b += [P(f"The main study applies the five conditions of Chapter 5 to {int(base.loc['E0','n_docs'])} de-identified hospital courses "
            f"from MIMIC-IV (the Brief Hospital Course sections of the ann-pt-summ documents, Section 3.4), each paired with the "
            f"discharge instructions that the treating clinician actually wrote for the patient. Summaries were generated by "
            f"Qwen2.5-7B-Instruct running locally on the author's computer (Section 4.11), so that no protected text left the "
            f"machine; retrieval conditions were required to cite the excerpt behind every sentence; and every summary, including "
            f"the doctor-written instructions, was scored by the judge selected in Chapter 6 ({judge}, {mode} evidence, threshold "
            f"{tau:.2f}). Header lines and abstentions are excluded from the claim set as in Chapter 5.")]
    b += [("h2", "7.2 Descriptive Statistics")]
    b += [P(f"[[tab:mdesc]] summarizes the outputs. The doctor-written instructions average {base.loc['REF','words_mean']:.0f} words and "
            f"{base.loc['REF','claims_mean']:.1f} claims; the LLM conditions produce between {base.loc[[c for c in conds if c not in ('REF','E2')],'words_mean'].min():.0f} and "
            f"{base.loc[[c for c in conds if c not in ('REF','E2')],'words_mean'].max():.0f} words. The verified condition wrote {base.loc['E3','abstentions_mean']:.1f} abstentions per "
            f"summary on average." if "E3" in conds else ""),
          ("table", dict(label="mdesc", caption="Length, number of claims and abstentions per summary in the main study (per-document means).",
                         columns=["Condition", "Documents", "Words", "Claims", "Abstentions"], widths=[2.6, 0.9, 1.0, 1.0, 1.0], font=10,
                         rows=[[NAME.get(c, c), str(int(base.loc[c, 'n_docs'])), f"{base.loc[c,'words_mean']:.0f}", f"{base.loc[c,'claims_mean']:.1f}", f"{base.loc[c,'abstentions_mean']:.1f}"] for c in conds]))]
    b += [("h2", "7.3 Unsupported Fact Rate and Contradiction Rate")]
    rows = []
    for m in ("UFR", "CR"):
        for c in [x for x in ORDER if x in base.index]:
            t0 = T(m, f"{c} vs E0"); t1 = T(m, f"{c} vs E1")
            rows.append([m if c == conds[0] else "", NAME.get(c, c), f3(base.loc[c, f"{m}_mean"]), f3(base.loc[c, f"{m}_median"]),
                         (f"{signed(t0.delta_mean)} ({fpn(t0.p)})" if t0 is not None else "—"), (f"{signed(t1.delta_mean)} ({fpn(t1.p)})" if t1 is not None else "—")])
    b += [P(f"[[tab:mrates]] gives the rates and the paired comparisons against the zero-context baseline and against excerpt-only RAG, "
            f"and [[fig:mbox]] the distributions. "
            + " ".join(f"{NAME.get(c,c)} {direction(T('UFR', f'{c} vs E0'))} E0 in UFR ({f3(base.loc[c,'UFR_mean'])} versus {f3(base.loc['E0','UFR_mean'])}, {fp(T('UFR', f'{c} vs E0').p) if T('UFR', f'{c} vs E0') is not None else ''}) "
                       f"and {direction(T('CR', f'{c} vs E0'))} E0 in CR ({f3(base.loc[c,'CR_mean'])} versus {f3(base.loc['E0','CR_mean'])}, {fp(T('CR', f'{c} vs E0').p) if T('CR', f'{c} vs E0') is not None else ''})."
                       for c in conds if c not in ("E0",))),
          ("table", dict(label="mrates", caption="Per-document mean and median UFR and CR in the main study, with paired mean differences and two-sided Wilcoxon p-values against E0 and against E1 (negative differences favour the row condition).",
                         columns=["Metric", "Condition", "Mean", "Median", "Δ vs E0 (p)", "Δ vs E1 (p)"], widths=[0.6, 2.4, 0.7, 0.7, 1.05, 1.05], font=9.5, rows=rows)),
          ("figure", dict(label="mbox", path="results/fig_mimic_box.png", width=6.5, caption="Per-document UFR (left) and CR (right) in the main study under each condition and for the doctor-written instructions."))]
    if ref is not None and "REF" in base.index:
        b += [P(f"The doctor-written instructions provide a human reference point on the same documents: under the same judge they receive a mean UFR of "
                f"{f3(base.loc['REF','UFR_mean'])} and CR of {f3(base.loc['REF','CR_mean'])}, while the medical experts marked {ref.expert_spans.sum()} unsupported spans in them. "
                + " ".join(f"{NAME.get(c,c)} {direction(T('UFR', f'{c} vs REF'))} the doctor-written instructions in UFR ({fp(T('UFR', f'{c} vs REF').p)})." for c in conds if c != 'REF' and T('UFR', f'{c} vs REF') is not None))]
    b += [("h2", "7.4 Coverage of the Clinician's Instructions")]
    rows = [[NAME.get(c, c), pct(base.loc[c, "coverage_ref_mean"]), (f"{signed(T('coverage_ref', f'{c} vs E0').delta_mean)} ({fpn(T('coverage_ref', f'{c} vs E0').p)})" if T('coverage_ref', f'{c} vs E0') is not None else "—"),
             (f"{signed(T('coverage_ref', f'{c} vs E1').delta_mean)} ({fpn(T('coverage_ref', f'{c} vs E1').p)})" if T('coverage_ref', f'{c} vs E1') is not None else "—")] for c in conds if c != "REF"]
    b += [P(f"Because every document has the discharge instructions its clinician wrote, omission can be measured directly: the share of "
            f"the clinician's sentences that the generated summary supports, judged by the same model in the reverse direction "
            f"(Section 4.11). [[tab:mcov]] and [[fig:mcov]] report it. "
            + " ".join(f"{NAME.get(c,c)} covered {pct(base.loc[c,'coverage_ref_mean'])} of the clinician's sentences" + (f" ({direction(T('coverage_ref', f'{c} vs E0'), False).replace('was lower than','less than').replace('was higher than','more than')} E0, {fp(T('coverage_ref', f'{c} vs E0').p)})" if T('coverage_ref', f'{c} vs E0') is not None else "") + "." for c in conds if c != "REF")),
          ("table", dict(label="mcov", caption="Coverage of the doctor-written discharge instructions: mean share of the clinician's sentences supported by the generated summary, with paired differences against E0 and E1.",
                         columns=["Condition", "Coverage", "Δ vs E0 (p)", "Δ vs E1 (p)"], widths=[2.8, 1.0, 1.35, 1.35], font=10, rows=rows)),
          ("figure", dict(label="mcov", path="results/fig_mimic_coverage.png", width=5.6, caption="Coverage of the clinician's discharge instructions per document under each condition."))]
    cited = base[base.cited_claims > 0]
    if len(cited):
        b += [("h2", "7.5 Citation Accuracy")]
        b += [P("Retrieval conditions were required to cite, after every sentence, the excerpt on which it is based. Citation accuracy "
                "is the share of cited claims whose cited excerpts support the claim according to the judge. "
                + " ".join(f"{NAME.get(c,c)} cited {int(base.loc[c,'cited_claims'])} claims with accuracy {pct(base.loc[c,'citation_accuracy_mean'])}." for c in cited.index)
                + " Citations make the judge's task easier, because the model names the passage it used, and they make review by a "
                "clinician faster; an inaccurate citation is itself a detectable error.")]
    if abl is not None and len(abl):
        b += [("h2", "7.6 Retrieval Ablations")]
        rows = []
        for v in [x for x in VAR if x != "base"]:
            r = {m: abl[(abl.metric == m) & (abl.variant == v)] for m in ("UFR", "CR", "coverage_ref", "citation_accuracy")}
            rows.append([VAR[v]] + [(f"{signed(r[m].delta_mean.iloc[0])} ({fpn(r[m].p.iloc[0])})" if len(r[m]) else "—") for m in ("UFR", "CR", "coverage_ref", "citation_accuracy")])
        b += [P("Six variants of E1 change one retrieval setting at a time (Section 4.11). [[tab:mabl]] reports the paired difference of each "
                "variant from the base configuration."),
              ("table", dict(label="mabl", caption="Retrieval ablations: paired mean difference from the E1 base configuration (5-sentence chunks, top-3, dense retrieval, citations required) with Wilcoxon p-values. Negative UFR and CR differences and positive coverage and citation differences favour the variant.",
                             columns=["Variant", "Δ UFR (p)", "Δ CR (p)", "Δ coverage (p)", "Δ citation accuracy (p)"], widths=[2.3, 1.05, 1.05, 1.05, 1.05], font=9.5, rows=rows))]
    if qa is not None and len(qa):
        b += [("h2", "7.7 Question-Answering Pilot")]
        tot = qa[qa.question == "all"].set_index("condition")
        b += [P(f"Three questions per hospital course, about medications, follow-up and warning signs, were answered by the local model "
                f"from the full course (QA-E0) or from three retrieved excerpts (QA-E1), with the instruction to answer \"Not stated in the "
                f"note.\" when the course is silent (Section 4.12). [[tab:mqa]] reports abstention rates, the judge's rates on the answered "
                f"questions, and the share of answer sentences supported by the clinician's own discharge instructions. "
                + " ".join(f"{c} abstained on {pct0(tot.loc[c,'abstention_rate'])} of questions, with UFR {f3(tot.loc[c,'UFR_mean'])} and {pct0(tot.loc[c,'ref_support_mean'])} of answer sentences supported by the clinician's instructions." for c in tot.index)),
              ("table", dict(label="mqa", caption="Question-answering pilot: abstention rate, judge rates on answered questions, and agreement with the clinician's discharge instructions, by question type and condition.",
                             columns=["Condition", "Question", "n", "Abstained", "UFR", "CR", "Supported by clinician's instructions", "Words"],
                             widths=[0.9, 1.1, 0.5, 0.8, 0.6, 0.6, 1.4, 0.6], font=9.5,
                             rows=[[r.condition, r.question.replace("_", " "), str(int(r.n)), pct0(r.abstention_rate), f3(r.UFR_mean), f3(r.CR_mean), pct0(r.ref_support_mean), f"{r.words_mean:.0f}"] for _, r in qa.sort_values(["condition", "question"]).iterrows()]))]
    b += [("h2", "7.8 Summary of the Main Study")]
    lines = []
    for c in [x for x in ("E1", "E1b", "E3", "E2") if x in base.index]:
        tu, tc, tcov = T("UFR", f"{c} vs E0"), T("CR", f"{c} vs E0"), T("coverage_ref", f"{c} vs E0")
        lines.append(f"**{NAME.get(c,c)}** {direction(tu)} E0 in unsupported facts ({f3(base.loc[c,'UFR_mean'])} versus {f3(base.loc['E0','UFR_mean'])}"
                     + (f", {fp(tu.p)}" if tu is not None else "") + f"), {direction(tc)} E0 in contradictions" + (f" ({fp(tc.p)})" if tc is not None else "")
                     + f", and covered {pct(base.loc[c,'coverage_ref_mean'])} of the clinician's instructions" + (f" ({fp(tcov.p)} versus E0)" if tcov is not None else "") + ".")
    b += [("bullets", lines)]
    return b
