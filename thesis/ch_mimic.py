MODE_NAMES = {"top3": "top-3 sentence evidence", "doc": "whole-course evidence"}


def direction(t, metric_lower_is_better=True):
    if t is None or (isinstance(t.p, float) and np.isnan(t.p)):
        return "did not differ from"
    if t.p >= 0.05:
        return "did not differ significantly from"
    return "was lower than" if t.delta_mean < 0 else "was higher than"


def adj(t):
    """'a lower' / 'a higher' / 'a similar' for 'condition had <adj> UFR than E0'."""
    if t is None or (isinstance(t.p, float) and np.isnan(t.p)) or t.p >= 0.05:
        return "a similar"
    return "a lower" if t.delta_mean < 0 else "a higher"


def rate_sentence(base, T, c, ref, fmt=f3):
    """One sentence comparing condition c with ref on UFR and CR."""
    tu, tc = T("UFR", f"{c} vs {ref}"), T("CR", f"{c} vs {ref}")
    if tu is None and tc is None:
        return ""
    pu = f", {fp(tu.p)}" if tu is not None else ""; pc = f", {fp(tc.p)}" if tc is not None else ""
    return (f"{NAME.get(c, c)} had {adj(tu)} UFR ({fmt(base.loc[c, 'UFR_mean'])} versus {fmt(base.loc[ref, 'UFR_mean'])}{pu}) and "
            f"{adj(tc)} CR ({fmt(base.loc[c, 'CR_mean'])} versus {fmt(base.loc[ref, 'CR_mean'])}{pc}) compared with {NAME.get(ref, ref) if ref != 'E0' else 'E0'}.")


def _join(names):
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def grouped_vs_ref(base, T, conds, metric="UFR"):
    """Group conditions by how they compare with the doctor-written instructions (short condition names)."""
    hi, lo, same = [], [], []
    for c in conds:
        t = T(metric, f"{c} vs REF")
        if t is None:
            continue
        (same if t.p >= 0.05 else (lo if t.delta_mean < 0 else hi)).append((c, t))
    def pmax(group):
        m = max(t.p for _, t in group)
        return ("all " if len(group) > 1 else "") + (f"p ≤ {m:.3f}" if m >= 0.001 else "p < 0.001")
    parts = []
    if hi:
        parts.append(f"{_join([c for c, _ in hi])} received a higher {metric} than the clinician's instructions ({pmax(hi)})")
    if lo:
        parts.append(f"{_join([c for c, _ in lo])} received a lower {metric} than the clinician's instructions ({pmax(lo)})")
    if same:
        parts.append(f"{_join([c for c, _ in same])} did not differ significantly from them (" + ("smallest " if len(same) > 1 else "") + f"{fp(min(t.p for _, t in same))})")
    return "; ".join(parts) + "." if parts else ""


